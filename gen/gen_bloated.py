"""Generate bloated-EOA scenario constants from the execution-specs model.

Run from the execution-specs repo root:

    PYTHONPATH=$PWD uv run python \
        /path/to/spamoor-eels-benchmarks/gen/gen_bloated.py \
        --gas 200 --out-dir /path/to/spamoor-eels-benchmarks
"""

import argparse
from pathlib import Path
from typing import Any

from execution_testing import (
    Bytecode,
    Hash,
    IteratingBytecode,
    Op,
    RecipientType,
    While,
)
from execution_testing.forks import Amsterdam, Osaka

from tests.benchmark.helper.storage import START_SLOT

FORKS = {"Amsterdam": Amsterdam, "Osaka": Osaka}

# test_sload.py:44
LOOP_GAS_THRESHOLD = 0xFFFF


def deploy_initcode(runtime: bytes) -> bytes:
    """Minimal constructor that returns *runtime*."""
    header = len(Op.CODECOPY(0, 0, 0)) + len(Op.RETURN(0, 0))
    code = Op.CODECOPY(0, header, len(runtime)) + Op.RETURN(0, len(runtime))
    return bytes(code) + runtime


def sload_runtime() -> Bytecode:
    """Mirror test_sload_bloated's delegated runtime (NO_CACHE)."""
    slot_access = Op.DUP1 + Op.SLOAD + Op.POP
    return (
        Op.PUSH0
        + Op.SLOAD  # index = storage[0]
        + While(
            body=slot_access + Op.PUSH1(1) + Op.ADD,
            condition=Op.GT(Op.GAS, LOOP_GAS_THRESHOLD),
        )
        + Op.PUSH0
        + Op.SSTORE  # storage[0] = index
    )


def sstore_runtime(existing_slots: bool, write_new_value: bool) -> Any:
    """Mirror test_sstore_bloated's delegated runtime (NO_CACHE)."""
    metadata: dict[str, Any] = {"key_warm": False}
    initial = int(existing_slots)
    metadata["original_value"] = initial
    metadata["current_value"] = initial
    metadata["new_value"] = initial + int(write_new_value)

    setup = Op.CALLDATALOAD(32) + Op.CALLDATALOAD(0)
    loop = Op.JUMPDEST
    if write_new_value:
        loop += (
            Op.DUP1 + Op.DUP1 + Op.PUSH1(1) + Op.ADD + Op.SWAP1
            + Op.SSTORE(**metadata)
        )
    else:
        push_value = Op.DUP1 if existing_slots else Op.PUSH1(0)
        loop += push_value + Op.DUP2 + Op.SSTORE(**metadata)
    loop += (
        Op.PUSH1(1) + Op.ADD + Op.DUP2 + Op.DUP2 + Op.LT
        + Op.PUSH1(len(setup)) + Op.JUMPI
    )
    return IteratingBytecode(setup=setup, iterating=loop, cleanup=Op.STOP)


def sstore_calldata(iteration_count: int, start_iteration: int) -> bytes:
    """Verbatim from test_sstore.py:136-137 (exclusive end slot)."""
    return Hash(start_iteration) + Hash(start_iteration + iteration_count)


def emit_sload(fork: Any, gas_limit: int) -> list[str]:
    """Build the sloadbloated constants."""
    runtime = bytes(sload_runtime())
    cap = fork.transaction_gas_limit_cap() or gas_limit
    minimum = fork.transaction_intrinsic_cost_calculator()(
        recipient_type=RecipientType.DELEGATION_7702
    ) + fork.transaction_top_frame_gas_calculator()(
        recipient_type=RecipientType.DELEGATION_7702
    )
    gas_limits, remaining = [], gas_limit
    while remaining >= minimum:
        this = min(remaining, cap)
        gas_limits.append(this)
        remaining -= this

    return [
        "// Code generated by gen/gen_bloated.py. DO NOT EDIT.",
        "//",
        f"// fork={fork.name()} blockGasLimit={gas_limit}"
        f" transactions={len(gas_limits)}",
        "// The loop is gas-bounded and resumes from storage slot 0, so the",
        "// transactions carry no calldata.",
        "",
        "package sloadbloated",
        "",
        'import "github.com/ethereum/go-ethereum/common"',
        "",
        "// RuntimeInitcode deploys the code the bloated EOA delegates to.",
        f'var RuntimeInitcode = common.FromHex('
        f'"0x{deploy_initcode(runtime).hex()}")',
        "",
        "// SetterInitcode deploys the contract that rewrites slot 0, which is",
        "// the loop cursor. Delegate to it to restart a sweep.",
        f'var SetterInitcode = common.FromHex('
        f'"0x{deploy_initcode(bytes(Op.SSTORE(0, Op.CALLDATALOAD(0)))).hex()}")',
        "",
        "// GasLimits is one entry per transaction of the benchmark block.",
        "var GasLimits = []uint64{",
        *[f"\t{g}," for g in gas_limits],
        "}",
        "",
        "// StartSlotExisting is the slot-0 cursor value for a bloated EOA",
        "// whose slots are already populated; StartSlotNew targets empty ones.",
        "const StartSlotExisting = 1",
        f'var StartSlotNew = common.FromHex("0x{START_SLOT:064x}")',
        "",
    ]


def emit_sstore(fork: Any, gas_limit: int, existing: bool,
                write_new: bool) -> list[str]:
    """Build the sstorebloated constants."""
    code = sstore_runtime(existing, write_new)
    start = 1 if existing else START_SLOT
    counts = list(
        code.tx_iterations_by_gas_limit(
            fork=fork, gas_limit=gas_limit, start_iteration=start,
            calldata=sstore_calldata,
            recipient_type=RecipientType.DELEGATION_7702,
        )
    )
    rows, slot = [], start
    for count in counts:
        tx_gas = code.tx_gas_limit_by_iteration_count(
            fork=fork, iteration_count=count, start_iteration=slot,
            include_state_gas_reservoir=True, calldata=sstore_calldata,
            recipient_type=RecipientType.DELEGATION_7702,
        )
        rows.append((count, slot, sstore_calldata(count, slot), tx_gas))
        slot += count

    lines = [
        "// Code generated by gen/gen_bloated.py. DO NOT EDIT.",
        "//",
        f"// fork={fork.name()} blockGasLimit={gas_limit}"
        f" transactions={len(rows)} iterations={sum(counts)}",
        f"// existingSlots={existing} writeNewValue={write_new}"
        f" (slot {int(existing)} -> {int(existing) + int(write_new)})",
        f"// slot range {start} .. {slot}",
        "",
        "package sstorebloated",
        "",
        'import "github.com/ethereum/go-ethereum/common"',
        "",
        "// RuntimeInitcode deploys the code the bloated EOA delegates to.",
        f'var RuntimeInitcode = common.FromHex('
        f'"0x{deploy_initcode(bytes(code)).hex()}")',
        "",
        "// TxSpec is one transaction of the benchmark block.",
        "type TxSpec struct {",
        "\tCallData []byte",
        "\tGas      uint64",
        "}",
        "",
        "// TxSpecs is the benchmark block, replayed in order and then looped.",
        "var TxSpecs = []TxSpec{",
    ]
    for count, slot0, data, tx_gas in rows:
        lines.append(
            f'\t{{common.FromHex("0x{data.hex()}"), {tx_gas}}},'
            f" // {count} slots from {slot0}"
        )
    lines += ["}", ""]
    return lines


def main() -> None:
    """Emit both Go constant files."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--gas", type=int, default=200)
    parser.add_argument("--fork", default="Amsterdam", choices=list(FORKS))
    parser.add_argument("--existing-slots", action="store_true")
    parser.add_argument("--write-new-value", action="store_true")
    parser.add_argument("--out-dir", required=True, type=Path)
    args = parser.parse_args()

    fork = FORKS[args.fork]
    gas_limit = args.gas * 1_000_000

    sload = args.out_dir / "sloadbloated" / "constants.go"
    sload.parent.mkdir(parents=True, exist_ok=True)
    sload.write_text("\n".join(emit_sload(fork, gas_limit)))
    print(f"wrote {sload}")

    sstore = args.out_dir / "sstorebloated" / "constants.go"
    sstore.parent.mkdir(parents=True, exist_ok=True)
    sstore.write_text("\n".join(emit_sstore(
        fork, gas_limit, args.existing_slots, args.write_new_value)))
    print(f"wrote {sstore}")


if __name__ == "__main__":
    main()
